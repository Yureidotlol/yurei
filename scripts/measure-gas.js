// Plays every stage of the protocol on a local Hardhat chain and records gas per call.
// Writes results/GAS.md. Run: npx hardhat run scripts/measure-gas.js
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");
const { ethers } = hre;
const { time } = require("@nomicfoundation/hardhat-network-helpers");
const H = require("../test/helpers");

const GAS = {};
async function g(label, txPromise) {
  const rc = await (await txPromise).wait();
  (GAS[label] ||= []).push(Number(rc.gasUsed));
  return rc;
}

async function main() {
  const ctx = await H.deploy();
  const { oracle, game, executor, watcher, requester, recipient, modelId } = ctx;
  const seal = await H.makeSeal(ctx);
  const input = H.findInput(1);
  const prog = H.prog;

  // honest path with a seal action
  let rc = await g("request (with seal check)", oracle.connect(requester).request(modelId, input, H.USDG(2), seal.target, recipient.address, H.USDG(4)));
  let id = oracle.interface.parseLog(rc.logs.find((l) => l.address === oracle.target)).args.id;
  const honest = new H.Executor(H.program); const a = honest.execute(input);
  await g("answer (2 Merkle proofs, bond)", oracle.connect(executor).answer(id, a.traceRoot, a.finalState, a.startProof, a.endProof));
  await time.increase(H.WINDOW + 1);
  await g("finalize (pay executor, seal acts)", oracle.finalize(id));

  // dishonest path: a full dispute
  const k = H.lastingCorruptions(input)[Math.floor(H.lastingCorruptions(input).length / 2)];
  rc = await g("request (no seal)", oracle.connect(requester).request(modelId, input, H.USDG(2), ethers.ZeroAddress, ethers.ZeroAddress, 0));
  id = oracle.interface.parseLog(rc.logs.find((l) => l.address === oracle.target)).args.id;
  const liar = new H.Executor(H.program, { corruptAt: k }); const la = liar.execute(input);
  await oracle.connect(executor).answer(id, la.traceRoot, la.finalState, la.startProof, la.endProof);
  const w = new H.Challenger(H.program); w.watch(input);
  const gameId = await oracle.connect(watcher).challenge.staticCall(id);
  await g("challenge (bond, open game)", oracle.connect(watcher).challenge(id));
  let rounds = 0;
  for (;;) {
    const st = await game.games(gameId), turn = Number(st.turn);
    if (turn === 1) { const mid = Number((st.lo + st.hi) / 2n); const r = liar.reveal(mid); await g("bisect (reveal + Merkle proof)", game.connect(executor).bisect(gameId, r.hash, r.proof)); rounds++; }
    else if (turn === 2) await g("respond (agree / disagree)", game.connect(watcher).respond(gameId, w.agrees(Number(st.mid), st.midHash)));
    else if (turn === 3) { const lo = Number(st.lo); await g("oneStep (execute 1 instruction, settle bonds)", game.connect(watcher).oneStep(gameId, w.stateAt(lo), H.program[lo], prog.tree.proof(lo))); break; }
    else break;
  }

  const avg = (xs) => Math.round(xs.reduce((s, x) => s + x, 0) / xs.length);
  const order = ["request (with seal check)", "answer (2 Merkle proofs, bond)", "finalize (pay executor, seal acts)", "request (no seal)", "challenge (bond, open game)", "bisect (reveal + Merkle proof)", "respond (agree / disagree)", "oneStep (execute 1 instruction, settle bonds)"];
  const rowsMd = order.filter((k2) => GAS[k2]).map((k2) => `| ${k2} | ${GAS[k2].length} | ${avg(GAS[k2]).toLocaleString("en-US")} |`).join("\n");
  const honestTotal = avg(GAS["request (with seal check)"]) + avg(GAS["answer (2 Merkle proofs, bond)"]) + avg(GAS["finalize (pay executor, seal acts)"]);
  const disputeTotal = avg(GAS["challenge (bond, open game)"]) + GAS["bisect (reveal + Merkle proof)"].reduce((s, x) => s + x, 0) + GAS["respond (agree / disagree)"].reduce((s, x) => s + x, 0) + avg(GAS["oneStep (execute 1 instruction, settle bonds)"]);

  const md = `# Gas, measured

Generated by \`npm run gas\` (scripts/measure-gas.js) on ${new Date().toISOString().slice(0, 10)}, on a local
Hardhat network (Solidity 0.8.28, optimizer 200 runs, via-IR, cancun). These are execution gas units,
not mainnet receipts. Nothing in this repository has been deployed to Robinhood Chain yet.

Model: toy-0, ${H.program.length} steps. Dispute: faulty step ${k}, settled in ${rounds} rounds.

| Call | Times called | Gas (mean) |
|---|---:|---:|
${rowsMd}

| Path | Total gas |
|---|---:|
| Honest answer, end to end (request + answer + finalize with seal action) | ${honestTotal.toLocaleString("en-US")} |
| Full dispute (challenge + ${rounds} rounds + one step) | ${disputeTotal.toLocaleString("en-US")} |

**Reading this.** An honest answer costs a fixed amount of gas whatever the model's size: the
chain checks two Merkle proofs and never runs the model. A dispute adds one
bisect and one respond per round and a single instruction at the end. On an Arbitrum Orbit chain
such as Robinhood Chain the fee is L2 execution gas times the gas price, plus a charge for posting
calldata to the parent chain; this table covers the first part only.
`;
  fs.writeFileSync(path.join(__dirname, "..", "results", "GAS.md"), md);
  console.log(md);
}

main().catch((e) => { console.error(e); process.exit(1); });
