// Measures dispute rounds against trace length by actually playing the bisection game
// on synthetic traces (state i is just the number i; a liar's trace is off from step k on).
// Writes results/BISECTION.md.
const fs = require("fs");
const path = require("path");
const { prng } = require("../reference/model");

function play(n, k) {
  // honest state hash at i: i ; liar's: i for i <= k, i + 0.5 for i > k
  let lo = 0, hi = n, rounds = 0;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    rounds++;
    const liar = mid > k ? mid + 0.5 : mid;
    if (liar === mid) lo = mid; else hi = mid;
  }
  return { rounds, step: lo };
}

const rnd = prng(2026);
const sizes = [50, 1_000, 10_000, 100_000, 1_000_000, 16_777_216, 1_000_000_000];
const rows = [];
for (const n of sizes) {
  let max = 0, sum = 0, ok = true;
  const trials = 2000;
  for (let t = 0; t < trials; t++) {
    const k = Math.floor(rnd() * n);
    const { rounds, step } = play(n, k);
    if (step !== k) ok = false;
    max = Math.max(max, rounds); sum += rounds;
  }
  rows.push({ n, bound: Math.ceil(Math.log2(n)), max, avg: (sum / trials).toFixed(2), ok });
}

const fmt = (n) => n.toLocaleString("en-US");
const md = `# Bisection rounds vs trace length

Generated by \`npm run bench\` (scripts/bench-bisection.js) on ${new Date().toISOString().slice(0, 10)}.

For each trace length, 2,000 disputes were played with the faulty step placed at random.
Every dispute located the faulty step exactly, and the chain re-executed one step each time.

| Trace length (steps) | ⌈log₂ n⌉ | Max rounds observed | Mean rounds | Faulty step found |
|---:|---:|---:|---:|:---:|
${rows.map((r) => `| ${fmt(r.n)} | ${r.bound} | ${r.max} | ${r.avg} | ${r.ok ? "2000 / 2000" : "FAILED"} |`).join("\n")}

**Reading this.** The work the chain does in a dispute is one reveal and one response per
round, plus one step at the end. Going from toy-0's 50 steps to a billion steps adds only
about 24 rounds. The cost of being honest does not grow with the size of the model; the
cost of a dispute grows with the logarithm of it.

These are synthetic traces. Gas per round on a real deployment is in [GAS.md](GAS.md).
`;
fs.writeFileSync(path.join(__dirname, "..", "results", "BISECTION.md"), md);
console.log(md);
